#!/usr/bin/env bash
set -Eeuo pipefail

# Miracle Cloud VM - standalone VM editor/reinstaller for manager.sh v6 configs.
# Default storage matches manager.sh: $HOME/vms. Override with VM_DIR=/path if needed.

RESET='\033[0m'; BOLD='\033[1m'; PURPLE='\033[1;35m'; GOLD='\033[1;33m'; CYAN='\033[1;36m'; GREEN='\033[1;32m'; RED='\033[1;31m'; GRAY='\033[1;90m'
info(){ printf "${CYAN}[MIRACLE • INFO]${RESET} %s\n" "$*"; }
ok(){ printf "${GREEN}[MIRACLE • OK]${RESET} %s\n" "$*"; }
warn(){ printf "${GOLD}[MIRACLE • WARN]${RESET} %s\n" "$*"; }
err(){ printf "${RED}[MIRACLE • ERROR]${RESET} %s\n" "$*" >&2; }
die(){ err "$*"; exit 1; }

[[ $EUID -eq 0 ]] || die "Run with sudo: sudo editvm.sh"
for cmd in qemu-img cloud-localds wget openssl awk sed find sort; do command -v "$cmd" >/dev/null 2>&1 || die "Missing dependency '$cmd'. Install qemu-utils cloud-image-utils wget openssl coreutils."
done

VM_DIR="${VM_DIR:-$HOME/vms}"
[[ -d "$VM_DIR" ]] || die "VM directory not found: $VM_DIR. Set VM_DIR=/path/to/vms if your manager uses a different directory."
mapfile -t VM_LIST < <(find "$VM_DIR" -maxdepth 1 -type f -name '*.conf' -printf '%f\n' | sed 's/\.conf$//' | sort)
((${#VM_LIST[@]} > 0)) || die "No VM .conf files found in $VM_DIR"

clear 2>/dev/null || true
printf "${PURPLE}╔══════════════════════════════════════════════════════════════════════╗${RESET}\n"
printf "${PURPLE}║${GOLD}                 ✦ MIRACLE CLOUD VM • EDITOR ✦                        ${PURPLE}║${RESET}\n"
printf "${PURPLE}║${GRAY}             Configuration • Resources • Reinstall                    ${PURPLE}║${RESET}\n"
printf "${PURPLE}╚══════════════════════════════════════════════════════════════════════╝${RESET}\n\n"
printf 'VM directory: %s\n\n' "$VM_DIR"
for i in "${!VM_LIST[@]}"; do printf "  ${GOLD}%2d)${RESET} %s\n" "$((i+1))" "${VM_LIST[$i]}"; done
printf '\n'
read -r -p 'Select VM number (0 to cancel): ' choice
[[ "$choice" == 0 ]] && exit 0
[[ "$choice" =~ ^[0-9]+$ ]] && ((choice >= 1 && choice <= ${#VM_LIST[@]})) || die 'Invalid VM selection.'
VM_NAME="${VM_LIST[$((choice-1))]}"
CONF="$VM_DIR/$VM_NAME.conf"
IMG="$VM_DIR/$VM_NAME.img"
SEED="$VM_DIR/$VM_NAME-seed.iso"
[[ -f "$CONF" ]] || die "Config not found: $CONF"

# This config format is generated by manager.sh. Only use configs you trust.
# shellcheck disable=SC1090
source "$CONF"
: "${VM_NAME:=$VM_NAME}" "${OS_TYPE:=ubuntu}" "${CODENAME:=noble}" "${IMG_URL:=}"
: "${HOSTNAME:=$VM_NAME}" "${USERNAME:=ubuntu}" "${PASSWORD:=}"
: "${DISK_SIZE:=20G}" "${MEMORY:=2048}" "${CPUS:=2}" "${SSH_PORT:=2222}"
: "${GUI_MODE:=false}" "${PORT_FORWARDS:=}" "${CPU_LABEL:=Ryzen EPYC Genoa (Zen 4 Class)}"
: "${CPU_MODEL:=EPYC-Genoa-v1}" "${CPU_FLAGS:=+ibpb,+virt-ssbd}" "${CREATED:=$(date '+%Y-%m-%d %H:%M:%S')}"
[[ -n "$IMG_URL" ]] || die 'IMG_URL is empty in this VM config; cannot reinstall safely.'

# Do not edit a running VM or replace its disk while QEMU is using it.
if pgrep -f "qemu-system-x86_64.*${IMG}" >/dev/null 2>&1; then
  die "VM '$VM_NAME' appears to be running. Stop it from the Miracle VM Manager first, then rerun this tool."
fi

valid_name(){ [[ "$1" =~ ^[a-zA-Z0-9_-]{1,63}$ ]]; }
valid_user(){ [[ "$1" =~ ^[a-z_][a-z0-9_-]*$ ]]; }
valid_size(){ [[ "$1" =~ ^[1-9][0-9]*[GgMm]$ ]]; }
valid_num(){ [[ "$1" =~ ^[1-9][0-9]*$ ]]; }

choose_cpu(){
  printf '\n${GOLD}Processor profiles${RESET}\n' | sed "s/\$/{RESET}/g" >/dev/null 2>&1 || true
  printf '  1) Ryzen EPYC Genoa (Zen 4 Class)\n  2) Ryzen EPYC Milan (Zen 3 Class)\n  3) Ryzen EPYC Rome (Zen 2 Class)\n  4) Ryzen EPYC Classic (Zen 1 Class)\n  5) Host passthrough (requires KVM)\n'
  read -r -p "Choose profile [current: $CPU_LABEL; Enter keeps current]: " c
  case "$c" in
    1) CPU_LABEL='Ryzen EPYC Genoa (Zen 4 Class)'; CPU_MODEL='EPYC-Genoa-v1'; CPU_FLAGS='+ibpb,+virt-ssbd' ;;
    2) CPU_LABEL='Ryzen EPYC Milan (Zen 3 Class)'; CPU_MODEL='EPYC-Milan-v2'; CPU_FLAGS='+ibpb,+virt-ssbd' ;;
    3) CPU_LABEL='Ryzen EPYC Rome (Zen 2 Class)'; CPU_MODEL='EPYC-Rome-v4'; CPU_FLAGS='+ibpb,+virt-ssbd' ;;
    4) CPU_LABEL='Ryzen EPYC Classic (Zen 1 Class)'; CPU_MODEL='EPYC-v4'; CPU_FLAGS='+ibpb,+virt-ssbd' ;;
    5) CPU_LABEL='Ryzen Host Passthrough (Native KVM)'; CPU_MODEL='host'; CPU_FLAGS='+virt-ssbd' ;;
    '') ;;
    *) warn 'Invalid selection; processor unchanged.' ;;
  esac
}

printf '\n${CYAN}Current configuration${RESET}\n' | sed "s/\$/{RESET}/g" >/dev/null 2>&1 || true
printf 'VM: %s | OS: %s %s\nCPU: %s (%s)\nRAM: %s MB | vCPU: %s | Disk: %s\nHostname: %s | User: %s | SSH port: %s\n' "$VM_NAME" "$OS_TYPE" "$CODENAME" "$CPU_LABEL" "$CPU_MODEL" "$MEMORY" "$CPUS" "$DISK_SIZE" "$HOSTNAME" "$USERNAME" "$SSH_PORT"
printf '\nLeave an entry empty to keep its current value.\n\n'

read -r -p "Hostname [$HOSTNAME]: " v; if [[ -n "$v" ]]; then valid_name "$v" || die 'Invalid hostname. Use letters, digits, _ or - (max 63 chars).'; HOSTNAME="$v"; fi
read -r -p "Username [$USERNAME]: " v; if [[ -n "$v" ]]; then valid_user "$v" || die 'Invalid username.'; USERNAME="$v"; fi
read -r -p "RAM in MB [$MEMORY]: " v; if [[ -n "$v" ]]; then valid_num "$v" || die 'RAM must be a positive integer in MB.'; MEMORY="$v"; fi
read -r -p "vCPU cores [$CPUS]: " v; if [[ -n "$v" ]]; then valid_num "$v" || die 'vCPU must be a positive integer.'; CPUS="$v"; fi
read -r -p "Disk size [$DISK_SIZE]: " v; if [[ -n "$v" ]]; then valid_size "$v" || die 'Disk size must look like 20G or 512M.'; DISK_SIZE="$v"; fi
choose_cpu
read -r -p "SSH host port [$SSH_PORT]: " v; if [[ -n "$v" ]]; then [[ "$v" =~ ^[0-9]+$ ]] && ((v >= 23 && v <= 65535)) || die 'SSH port must be between 23 and 65535.'; SSH_PORT="$v"; fi
read -r -p "Port forwards host:guest, comma-separated [${PORT_FORWARDS:-none}]: " v; if [[ -n "$v" ]]; then
  IFS=',' read -ra fwd <<< "$v"
  for pair in "${fwd[@]}"; do [[ "$pair" =~ ^[0-9]+:[0-9]+$ ]] || die "Invalid port forward: $pair"; a=${pair%%:*}; b=${pair##*:}; ((a>=1 && a<=65535 && b>=1 && b<=65535)) || die "Port out of range: $pair"; done
  PORT_FORWARDS="$v"
fi
read -r -p 'Enable GUI mode? (y/n) [current: '"$GUI_MODE"']: ' v
case "${v,,}" in y|yes) GUI_MODE=true;; n|no) GUI_MODE=false;; '') ;; *) die 'Enter y or n for GUI mode.';; esac
read -r -s -p 'New login password (leave empty to keep current): ' new_password; printf '\n'
[[ -n "$new_password" ]] && PASSWORD="$new_password"
[[ -n "$PASSWORD" ]] || die 'A non-empty password is required to generate cloud-init credentials.'

# Convert requested disk size to MiB for comparison and enforce non-shrinking disk edits.
size_mib(){ local n=${1%[GgMm]}; local u=${1: -1}; if [[ "$u" =~ [Gg] ]]; then echo $((n*1024)); else echo "$n"; fi; }
if [[ -f "$IMG" ]]; then
  old_mib=$(qemu-img info --output=json "$IMG" 2>/dev/null | awk -F: '/"virtual-size"/ {gsub(/[^0-9]/,"",$2); print int($2/1048576); exit}')
  new_mib=$(size_mib "$DISK_SIZE")
  if [[ -n "${old_mib:-}" ]] && (( new_mib < old_mib )); then die "Requested disk ($DISK_SIZE) is smaller than the current virtual disk (${old_mib} MiB). Disk shrinking is disabled to protect data."; fi
fi

printf '\n${GOLD}Reinstall warning${RESET}\n' | sed "s/\$/{RESET}/g" >/dev/null 2>&1 || true
warn 'Reinstall replaces the guest OS disk with a fresh cloud image. Existing guest files and applications will not be present in the new VM.'
warn 'The old disk will be preserved as a timestamped backup if there is enough free space.'
printf '\nPlanned configuration:\n  VM: %s\n  CPU: %s (%s)\n  RAM: %s MB | vCPU: %s | Disk: %s\n  Hostname: %s | User: %s | SSH port: %s\n\n' "$VM_NAME" "$CPU_LABEL" "$CPU_MODEL" "$MEMORY" "$CPUS" "$DISK_SIZE" "$HOSTNAME" "$USERNAME" "$SSH_PORT"
read -r -p "Type REINSTALL to continue and rebuild '$VM_NAME': " confirm
[[ "$confirm" == REINSTALL ]] || { info 'Cancelled; no changes made.'; exit 0; }

TMP_DIR=$(mktemp -d "$VM_DIR/.${VM_NAME}.reinstall.XXXXXX")
cleanup(){ rm -rf -- "$TMP_DIR"; }
trap cleanup EXIT

info "Downloading fresh image from configured OS source..."
wget -q --show-progress "$IMG_URL" -O "$TMP_DIR/source-image" || die 'Image download failed; original VM was not changed.'
qemu-img convert -p -O qcow2 "$TMP_DIR/source-image" "$TMP_DIR/new-disk.qcow2" || die 'Could not convert downloaded image; original VM was not changed.'
qemu-img resize "$TMP_DIR/new-disk.qcow2" "$DISK_SIZE" >/dev/null || die 'Could not set requested disk size; original VM was not changed.'

pass_hash=$(openssl passwd -6 "$PASSWORD" | tr -d '\n')
# cloud-init values are quoted where appropriate; hostname and username are validated above.
cat > "$TMP_DIR/user-data" <<EOF_CLOUD
#cloud-config
hostname: $HOSTNAME
manage_etc_hosts: true
ssh_pwauth: true
disable_root: true
users:
  - default
  - name: $USERNAME
    gecos: Miracle Cloud VM User
    groups: [adm, sudo]
    sudo: ALL=(ALL) NOPASSWD:ALL
    shell: /bin/bash
    lock_passwd: false
    passwd: '$pass_hash'
EOF_CLOUD
cat > "$TMP_DIR/meta-data" <<EOF_META
instance-id: iid-$VM_NAME-$(date +%s)
local-hostname: $HOSTNAME
EOF_META
cloud-localds "$TMP_DIR/new-seed.iso" "$TMP_DIR/user-data" "$TMP_DIR/meta-data" || die 'Failed to create cloud-init seed; original VM was not changed.'

# Save current config/disk/seed before swapping. Never overwrite an existing backup.
stamp=$(date '+%Y%m%d-%H%M%S')
if [[ -f "$IMG" ]]; then
  backup="$IMG.pre-reinstall-$stamp"
  info "Backing up current disk to $backup (this may require substantial free space)..."
  cp --reflink=auto --sparse=always -- "$IMG" "$backup" || die 'Disk backup failed; original VM was not changed.'
fi
if [[ -f "$SEED" ]]; then cp -a -- "$SEED" "$SEED.pre-reinstall-$stamp" || die 'Seed backup failed; original VM was not changed.'; fi
cp -a -- "$CONF" "$CONF.pre-reinstall-$stamp" || die 'Config backup failed; original VM was not changed.'

# Stage files in the same directory so rename is atomic on a single filesystem.
new_img="$VM_DIR/.${VM_NAME}.img.new.$$"
new_seed="$VM_DIR/.${VM_NAME}-seed.iso.new.$$"
cp -- "$TMP_DIR/new-disk.qcow2" "$new_img"
cp -- "$TMP_DIR/new-seed.iso" "$new_seed"
chmod 600 "$new_img" "$new_seed"
